// fmt('Round {n}', { n: 3 }) -> 'Round 3'
export function fmt(template, values = {}) {
  return String(template).replace(/\{(\w+)\}/g, (m, k) => (Object.hasOwn(values, k) ? String(values[k]) : m));
}
